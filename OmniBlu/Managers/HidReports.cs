namespace OmniBlu.Managers;

/// <summary>
/// HID over GATT data: the report map (what this PC tells the phone it is) and the input reports it sends.
/// This PC presents itself as a keyboard (report 1) and a mouse (report 2).
/// </summary>
public static class HidReports
{
    public const byte KeyboardReportId = 1;
    public const byte MouseReportId = 2;

    public const int KeyboardReportSize = 8;
    public const int MouseReportSize = 4;

    public const byte MouseLeftButton = 0x01;

    /// <summary>HID usage code of the Enter key.</summary>
    public const byte KeyEnter = 0x28;

    /// <summary>Keyboard report: modifiers, reserved, then up to 6 pressed keys. Mouse report: buttons, x, y, wheel.</summary>
    public static readonly byte[] ReportMap =
    {
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, KeyboardReportId,
          0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
          0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
          0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00,
        0xC0,
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, MouseReportId,
          0x09, 0x01, 0xA1, 0x00,
            0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
            0x95, 0x01, 0x75, 0x05, 0x81, 0x03,
            0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06,
          0xC0,
        0xC0,
    };

    /// <summary>HID Information: version 1.11, country 0, normally connectable.</summary>
    public static readonly byte[] HidInformation = { 0x11, 0x01, 0x00, 0x02 };

    public static byte[] KeyDown(byte usage, byte modifiers = 0) => new byte[] { modifiers, 0, usage, 0, 0, 0, 0, 0 };

    public static byte[] KeysUp() => new byte[KeyboardReportSize];

    public static byte[] Mouse(byte buttons, sbyte dx, sbyte dy, sbyte wheel) =>
        new[] { buttons, (byte)dx, (byte)dy, (byte)wheel };
}
